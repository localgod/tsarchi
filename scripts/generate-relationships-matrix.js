// scripts/generate-relationships-matrix.js
//
// Regenerates src/constants/relationships-matrix.mts from Archi's relationships matrix.
// Usage: node scripts/generate-relationships-matrix.js [archi-commit]
import fs from 'fs';
import path from 'path';

const commit = process.argv[2] || '6d236081d9460f063076dbb6225f8645c5f5a7a5';
const base = `https://raw.githubusercontent.com/archimatetool/archi/${commit}/com.archimatetool.model/model`;
const outFile = path.resolve('./src/constants/relationships-matrix.mts');

async function fetchText(name) {
  const response = await fetch(`${base}/${name}`);
  if (!response.ok) throw new Error(`Failed to fetch ${name}: ${response.status}`);
  return response.text();
}

const keysXml = await fetchText('relationships-keys.xml');
const matrixXml = await fetchText('relationships.xml');

const keys = [...keysXml.matchAll(/<key char="(\w)" relationship="(\w+)"/g)].map(([, char, type]) => [char, type]);

const rows = [];
for (const [, source, body] of matrixXml.matchAll(/<source concept="(\w+)">([\s\S]*?)<\/source>/g)) {
  const targets = [...body.matchAll(/<target concept="(\w+)" relations="(\w*)"/g)]
    .filter(([, , relations]) => relations !== '')
    .map(([, target, relations]) => `${target}: '${relations.toLowerCase()}'`);
  rows.push(`  ${source}: { ${targets.join(', ')} },`);
}

const output = `// Generated by scripts/generate-relationships-matrix.js. Do not edit.
// Source: https://github.com/archimatetool/archi/blob/${commit}/com.archimatetool.model/model/relationships.xml
// and relationships-keys.xml. "Relationship" stands for any relationship used as a source or target.

/** Letter used in the matrix for each relationship type. */
export const relationshipMatrixKeys: Readonly<Record<string, string>> = {
${keys.map(([char, type]) => `  ${char}: '${type}',`).join('\n')}
};

/** Allowed relationship letters from a source concept to a target concept. Missing pairs allow nothing. */
export const relationshipsMatrix: Readonly<Record<string, Readonly<Record<string, string>>>> = {
${rows.join('\n')}
};
`;

fs.writeFileSync(outFile, output);
console.log(`Wrote ${outFile} (${rows.length} source concepts, Archi ${commit})`);
